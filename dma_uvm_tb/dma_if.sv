// =============================================================================
// Interface   : dma_if.sv
// Description : Standard UVM SystemVerilog Interface for DMA
// =============================================================================
`timescale 1ns / 1ps

interface dma_if (input logic clk, input logic rst_n);

  // Physical Bus Signals
  logic        sample_tick;
  logic        spi_sample_ready;
  logic [15:0] spi_sample_data;
  logic [15:0] fir_sample_in;
  logic        fir_sample_valid_in;
  logic [15:0] fir_sample_out;
  logic        fir_sample_valid_out;
  logic [11:0] sbuf_waddr;
  logic [15:0] sbuf_wdata;
  logic        sbuf_we;
  logic        buf_swap_req;
  logic [7:0] m_axi_awid;
  logic [31:0] m_axi_awaddr;
  logic [7:0] m_axi_awlen;
  logic [2:0] m_axi_awsize;
  logic [1:0] m_axi_awburst;
  logic        m_axi_awlock;
  logic [3:0] m_axi_awcache;
  logic [2:0] m_axi_awprot;
  logic [3:0] m_axi_awqos;
  logic        m_axi_awvalid;
  logic        m_axi_awready;
  logic [31:0] m_axi_wdata;
  logic [3:0] m_axi_wstrb;
  logic        m_axi_wlast;
  logic        m_axi_wvalid;
  logic        m_axi_wready;
  logic [7:0] m_axi_bid;
  logic [1:0] m_axi_bresp;
  logic        m_axi_bvalid;
  logic        m_axi_bready;
  logic [7:0] m_axi_arid;
  logic [31:0] m_axi_araddr;
  logic [7:0] m_axi_arlen;
  logic [2:0] m_axi_arsize;
  logic [1:0] m_axi_arburst;
  logic        m_axi_arlock;
  logic [3:0] m_axi_arcache;
  logic [2:0] m_axi_arprot;
  logic [3:0] m_axi_arqos;
  logic        m_axi_arvalid;
  logic        m_axi_arready;
  logic [7:0] m_axi_rid;
  logic [31:0] m_axi_rdata;
  logic [1:0] m_axi_rresp;
  logic        m_axi_rlast;
  logic        m_axi_rvalid;
  logic        m_axi_rready;
  logic [31:0] s_axi_awaddr;
  logic        s_axi_awvalid;
  logic        s_axi_awready;
  logic [31:0] s_axi_wdata;
  logic [3:0] s_axi_wstrb;
  logic        s_axi_wvalid;
  logic        s_axi_wready;
  logic [1:0] s_axi_bresp;
  logic        s_axi_bvalid;
  logic        s_axi_bready;
  logic [31:0] s_axi_araddr;
  logic        s_axi_arvalid;
  logic        s_axi_arready;
  logic [31:0] s_axi_rdata;
  logic [1:0] s_axi_rresp;
  logic        s_axi_rvalid;
  logic        s_axi_rready;
  logic        irq_dma_done;
  logic        irq_dma_err;

  // Master Clocking Block (Driver perspective)
  clocking master_cb @(posedge clk);
    default input #1step output #1;
    output sample_tick;
    output spi_sample_ready;
    output spi_sample_data;
    input  fir_sample_in;
    input  fir_sample_valid_in;
    output fir_sample_out;
    output fir_sample_valid_out;
    input  sbuf_waddr;
    input  sbuf_wdata;
    input  sbuf_we;
    input  buf_swap_req;
    input  m_axi_awid;
    input  m_axi_awaddr;
    input  m_axi_awlen;
    input  m_axi_awsize;
    input  m_axi_awburst;
    input  m_axi_awlock;
    input  m_axi_awcache;
    input  m_axi_awprot;
    input  m_axi_awqos;
    input  m_axi_awvalid;
    output m_axi_awready;
    input  m_axi_wdata;
    input  m_axi_wstrb;
    input  m_axi_wlast;
    input  m_axi_wvalid;
    output m_axi_wready;
    output m_axi_bid;
    output m_axi_bresp;
    output m_axi_bvalid;
    input  m_axi_bready;
    input  m_axi_arid;
    input  m_axi_araddr;
    input  m_axi_arlen;
    input  m_axi_arsize;
    input  m_axi_arburst;
    input  m_axi_arlock;
    input  m_axi_arcache;
    input  m_axi_arprot;
    input  m_axi_arqos;
    input  m_axi_arvalid;
    output m_axi_arready;
    output m_axi_rid;
    output m_axi_rdata;
    output m_axi_rresp;
    output m_axi_rlast;
    output m_axi_rvalid;
    input  m_axi_rready;
    output s_axi_awaddr;
    output s_axi_awvalid;
    input  s_axi_awready;
    output s_axi_wdata;
    output s_axi_wstrb;
    output s_axi_wvalid;
    input  s_axi_wready;
    input  s_axi_bresp;
    input  s_axi_bvalid;
    output s_axi_bready;
    output s_axi_araddr;
    output s_axi_arvalid;
    input  s_axi_arready;
    input  s_axi_rdata;
    input  s_axi_rresp;
    input  s_axi_rvalid;
    output s_axi_rready;
    input  irq_dma_done;
    input  irq_dma_err;
  endclocking

  // Monitor Clocking Block (Passive sampling)
  clocking monitor_cb @(posedge clk);
    default input #1step output #1;
    input  sample_tick;
    input  spi_sample_ready;
    input  spi_sample_data;
    input  fir_sample_in;
    input  fir_sample_valid_in;
    input  fir_sample_out;
    input  fir_sample_valid_out;
    input  sbuf_waddr;
    input  sbuf_wdata;
    input  sbuf_we;
    input  buf_swap_req;
    input  m_axi_awid;
    input  m_axi_awaddr;
    input  m_axi_awlen;
    input  m_axi_awsize;
    input  m_axi_awburst;
    input  m_axi_awlock;
    input  m_axi_awcache;
    input  m_axi_awprot;
    input  m_axi_awqos;
    input  m_axi_awvalid;
    input  m_axi_awready;
    input  m_axi_wdata;
    input  m_axi_wstrb;
    input  m_axi_wlast;
    input  m_axi_wvalid;
    input  m_axi_wready;
    input  m_axi_bid;
    input  m_axi_bresp;
    input  m_axi_bvalid;
    input  m_axi_bready;
    input  m_axi_arid;
    input  m_axi_araddr;
    input  m_axi_arlen;
    input  m_axi_arsize;
    input  m_axi_arburst;
    input  m_axi_arlock;
    input  m_axi_arcache;
    input  m_axi_arprot;
    input  m_axi_arqos;
    input  m_axi_arvalid;
    input  m_axi_arready;
    input  m_axi_rid;
    input  m_axi_rdata;
    input  m_axi_rresp;
    input  m_axi_rlast;
    input  m_axi_rvalid;
    input  m_axi_rready;
    input  s_axi_awaddr;
    input  s_axi_awvalid;
    input  s_axi_awready;
    input  s_axi_wdata;
    input  s_axi_wstrb;
    input  s_axi_wvalid;
    input  s_axi_wready;
    input  s_axi_bresp;
    input  s_axi_bvalid;
    input  s_axi_bready;
    input  s_axi_araddr;
    input  s_axi_arvalid;
    input  s_axi_arready;
    input  s_axi_rdata;
    input  s_axi_rresp;
    input  s_axi_rvalid;
    input  s_axi_rready;
    input  irq_dma_done;
    input  irq_dma_err;
  endclocking

  // Modports
  modport master_mp (clocking master_cb, input clk, input rst_n);
  modport monitor_mp (clocking monitor_cb, input clk, input rst_n);

endinterface : dma_if
