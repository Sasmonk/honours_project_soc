/*
 * AXI Interconnect + AXI UART Top-Level Integration Module
 *
 * This module connects a 3-Master x 10-Slave AXI4 Interconnect to the AXI4-Lite
 * UART IP core.
 *
 * - Slave Interfaces (s00, s01, s02):
 *     Exposed to connect bus masters such as RISC-V CPU cores, DMA, and debug units.
 * - Master Port 00 (m00):
 *     Connected internally to the AXI UART IP core (axi_uart_top).
 * - Master Ports 01..09 (m01..m09):
 *     Exported to the top-level boundary for connecting additional peripherals
 *     (e.g., Boot ROM, RAM, AES Core, GPIO, Timers, etc.).
 * - UART Interface:
 *     uart_rx, uart_tx, and uart_irq are brought out to the top level.
